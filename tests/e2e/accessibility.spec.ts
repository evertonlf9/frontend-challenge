import { expect, test } from '@playwright/test'
import { prepare } from './support/api.js'

test.beforeEach(async ({ page }) => prepare(page))

test('painel permanece alcançável por teclado em viewport equivalente a zoom elevado', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 256 })
  const trigger = page.getByLabel('Acessibilidade', { exact: true })
  const panel = page.locator('.accessibility-panel')
  await trigger.focus()
  await page.keyboard.press('Enter')
  await page.keyboard.press('Tab')
  await expect(panel.getByRole('button', { name: 'Fechar acessibilidade' })).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Space')
  const firstParagraph = panel.locator('p').first()
  await page.keyboard.press('Tab')
  await expect(firstParagraph).toBeFocused()
  const firstBox = (await firstParagraph.boundingBox())!
  expect(firstBox.y).toBeGreaterThanOrEqual(0)
  expect(firstBox.y + firstBox.height).toBeLessThanOrEqual(256)
  await page.keyboard.press('Tab')
  const lastBox = (await panel.locator('p').last().boundingBox())!
  expect(lastBox.y).toBeGreaterThanOrEqual(0)
  expect(lastBox.y + lastBox.height).toBeLessThanOrEqual(256)
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})

test('painel de acessibilidade inclui título e textos na leitura por Tab', async ({ page }) => {
  const trigger = page.getByLabel('Acessibilidade', { exact: true })
  const panel = page.locator('.accessibility-panel')
  const toggle = panel.getByRole('button', { name: /^Leitura por Tab/ })
  const title = panel.getByRole('heading', { name: 'Acessibilidade' })
  const close = panel.getByRole('button', { name: 'Fechar acessibilidade' })
  const paragraphs = panel.locator('p')

  await trigger.focus()
  await page.keyboard.press('Enter')
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(toggle).toBeFocused()
  await page.keyboard.press('Space')
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')

  await page.keyboard.press('Tab')
  await expect(paragraphs.nth(0)).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(paragraphs.nth(1)).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(paragraphs.nth(0)).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(toggle).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(title).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()

  await page.keyboard.press('Escape')
  await expect(panel).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await page.keyboard.press('Enter')
  await page.keyboard.press('Tab')
  await expect(title).toBeFocused()
})

test('leitura do painel persiste ao recarregar e pode ser desativada', async ({ page }) => {
  const trigger = page.getByLabel('Acessibilidade', { exact: true })
  const panel = page.locator('.accessibility-panel')
  const toggle = panel.getByRole('button', { name: /^Leitura por Tab/ })
  const title = panel.getByRole('heading', { name: 'Acessibilidade' })
  const close = panel.getByRole('button', { name: 'Fechar acessibilidade' })

  await trigger.click()
  await toggle.click()
  await page.reload()
  await trigger.focus()
  await page.keyboard.press('Enter')
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Tab')
  await expect(title).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(toggle).toBeFocused()
  await page.keyboard.press('Space')
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(panel.locator('[data-reading-focus]')).toHaveCount(0)
  await page.keyboard.press('Shift+Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(trigger).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(toggle).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(panel.locator(':focus')).toHaveCount(0)
})
