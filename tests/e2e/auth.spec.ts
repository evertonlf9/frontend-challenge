import { expect, test } from '@playwright/test'
import { prepare } from './support/api.js'

test.beforeEach(async ({ page }) => prepare(page))

test('modal abre sobre o catálogo, alterna abas e restaura foco ao fechar', async ({ page }) => {
  const trigger = page.getByRole('link', { name: 'Entrar', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByLabel('E-mail', { exact: true })).toBeFocused()
  await expect(page.locator('.hero-art')).toBeVisible()
  await dialog.getByRole('link', { name: /Cri(ar|e)( uma)? conta/ }).click()
  await expect(page).toHaveURL(/register/)
  await expect(page.getByLabel('Confirmar senha', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page).toHaveURL((url) => url.pathname === '/' && (url.searchParams.get('page') ?? '1') === '1')
  await trigger.click()
  await page.getByRole('button', { name: 'Fechar autenticação' }).click()
  await expect(trigger).toBeFocused()
})

test('senha pode ser exibida e o cadastro rejeita confirmação diferente sem chamar a API', async ({ page }) => {
  let calls = 0
  page.on('request', (request) => { if (request.url().endsWith('/api/auth/register')) calls++ })
  await page.goto('/register')
  await page.getByLabel('Nome', { exact: true }).fill('Nova Pessoa')
  await page.getByLabel('E-mail', { exact: true }).fill('modal@example.test')
  await page.getByLabel('Senha', { exact: true }).fill('senha1234')
  await page.getByRole('button', { name: 'Mostrar senha', exact: true }).click()
  await expect(page.getByLabel('Senha', { exact: true })).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: 'Ocultar senha', exact: true }).click()
  await expect(page.getByLabel('Senha', { exact: true })).toHaveAttribute('type', 'password')
  await page.getByLabel('Confirmar senha', { exact: true }).fill('outrasenha')
  await page.getByRole('button', { name: /^Criar (conta|perfil)$/ }).click()
  await expect(page.getByRole('alert')).toHaveText('As senhas devem ser iguais.')
  expect(calls).toBe(0)
  await expect(page.getByLabel('Confirmar senha', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Confirmar senha', { exact: true }).fill('senha1234')
  await page.getByRole('button', { name: /^Criar (conta|perfil)$/ }).click()
  await expect(page).toHaveURL(/\/profile$/)
  await expect(page.getByRole('button', { name: 'Sair', exact: true })).toBeVisible()
  expect(calls).toBe(1)
})

test('login preserva filtros, trata credenciais inválidas e retorna ao catálogo', async ({ page }) => {
  await page.goto('/?page=2&network=ethereum&minPrice=0.1')
  await page.getByRole('link', { name: 'Entrar', exact: true }).click()
  await page.getByLabel('E-mail', { exact: true }).fill('ana.ribeiro@kurio.dev')
  await page.getByLabel('Senha', { exact: true }).fill('errada')
  await page.getByRole('button', { name: 'Entrar na conta' }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('Senha', { exact: true }).fill('kurio1234')
  await page.getByRole('button', { name: 'Entrar na conta' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page).toHaveURL(/network=ethereum/)
  expect(new URL(page.url()).searchParams.get('page')).toBe('2')
})

test('ações auxiliares explicam a integração e o teclado permanece no modal sem overflow', async ({ page }) => {
  await page.goto('/login')
  const dialog = page.getByRole('dialog')
  await page.getByRole('button', { name: 'Esqueceu a senha?' }).click()
  await expect(page.locator('#auth-recovery')).toContainText('ainda não está configurado')
  await page.getByRole('button', { name: 'Continuar com Google' }).click()
  await expect(dialog.getByRole('status').filter({ hasText: 'integração com Google' })).toBeVisible()
  await page.getByRole('button', { name: 'Continuar com Facebook' }).click()
  await expect(dialog.getByRole('status').filter({ hasText: 'integração com Facebook' })).toBeVisible()
  const last = dialog.getByRole('button', { name: /^Leitura por Tab/ })
  await last.focus()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Fechar autenticação' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(last).toBeFocused()
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})
