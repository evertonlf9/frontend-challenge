test('carteiras persistem metadados, opção secundária e promoção da carteira principal', async ({ page }) => {
  await loginUi(page)
  await page.getByRole('navigation', { name: 'Navegação do perfil' }).getByRole('link', { name: 'Carteiras', exact: true }).click()
  const secondary = page.getByRole('region', { name: 'Carteira secundária', exact: true })
  await secondary.getByRole('checkbox', { name: 'Igual à carteira principal' }).check()
  await expect(secondary.getByText('A carteira principal também será usada como carteira secundária.')).toBeVisible()
  await page.reload()
  await expect(secondary.getByRole('checkbox', { name: 'Igual à carteira principal' })).toBeChecked()
  await secondary.getByRole('checkbox', { name: 'Igual à carteira principal' }).uncheck()
  await secondary.getByRole('button', { name: 'Adicionar', exact: true }).click()
  let form = page.getByRole('form', { name: 'Nova carteira secundária', exact: true })
  await form.getByLabel('Apelido da carteira', { exact: true }).fill('Reserva')
  await form.getByLabel('Endereço da carteira', { exact: true }).fill('0x' + 'a'.repeat(40))
  await form.getByLabel('Rede', { exact: true }).selectOption('polygon')
  await form.getByLabel('Tipo de carteira', { exact: true }).selectOption('Coinbase Wallet')
  await form.getByLabel('Nome ENS', { exact: true }).fill('ana-reserva')
  await form.getByLabel('Código de indicação', { exact: true }).fill('KURIO-ANA')
  await form.getByLabel('ENS ou carteira secundária', { exact: true }).fill('ana.eth')
  await form.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Carteira salva.' })).toBeVisible()
  await page.reload()
  form = page.getByRole('form', { name: 'Editar Reserva', exact: true })
  await expect(form.getByLabel('Tipo de carteira', { exact: true })).toHaveValue('Coinbase Wallet')
  await expect(form.getByLabel('Nome ENS', { exact: true })).toHaveValue('ana-reserva')
  await expect(form.getByLabel('Código de indicação', { exact: true })).toHaveValue('KURIO-ANA')
  await expect(form.getByLabel('ENS ou carteira secundária', { exact: true })).toHaveValue('ana.eth')
  await form.getByRole('checkbox', { name: 'Usar como principal' }).check()
  await form.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  const primary = page.getByRole('region', { name: 'Carteira principal', exact: true })
  await expect(primary.getByRole('form', { name: 'Editar Reserva', exact: true })).toBeVisible()
  const response = await api<{ items: { label: string; isPrimary: boolean }[] }>(page, 'GET', '/wallets')
  expect(response.data!.items.filter((wallet) => wallet.isPrimary).map((wallet) => wallet.label)).toEqual(['Reserva'])
})

test('menu de conta navega para favoritos e atividade e ações auxiliares restauram o foco', async ({ page }) => {
  await loginUi(page)
  const navigation = page.getByRole('navigation', { name: 'Navegação do perfil' })
  await expect(navigation.locator('[aria-current="page"]')).toHaveCount(1)
  await navigation.getByRole('button', { name: 'Ofertas', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Ofertas', exact: true })).toContainText('ainda não está disponível')
  await page.keyboard.press('Escape')
  await expect(navigation.getByRole('button', { name: 'Ofertas', exact: true })).toBeFocused()
  await navigation.getByRole('link', { name: 'Lista de interesse', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Lista de interesse', exact: true })).toBeVisible()
  await expect(navigation.locator('[aria-current="page"]')).toHaveCount(1)
  await navigation.getByRole('link', { name: 'Atividade', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pedidos', exact: true })).toBeVisible()
})

test('comprovante abre pelo pedido, esclarece explorador simulado e fecha para a atividade', async ({ page }) => {
  await loginUi(page)
  const session = await api<{ session: { token: string } }>(page, 'GET', '/auth/session')
  const input = await orderInput(page, session.data!.session.token)
  const result = await api<{ id: string }>(page, 'POST', '/orders', { ...input, collector: { ...input.collector, walletProvider: 'MetaMask' } })
  expect(result.status).toBe(201)
  await page.goto('/orders/' + result.data!.id)
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: 'Compra confirmada' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Ver no Etherscan' }).click()
  await expect(dialog.getByRole('status')).toContainText('não possui registro no Etherscan')
  await expect(dialog.getByRole('status')).toHaveAttribute('tabindex', '0')
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('status')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.locator('summary')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(dialog.getByText('Colecionador', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Fechar comprovante' }).click()
  await expect(page.getByRole('heading', { name: 'Pedidos', exact: true })).toBeVisible()
  await page.getByRole('link').filter({ hasText: result.data!.id }).click()
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('heading', { name: 'Pedidos', exact: true })).toBeVisible()
})

test('API rejeita metadados inválidos sem alterar o perfil ou a carteira', async ({ page }) => {
  await loginUi(page)
  expect((await api(page, 'PATCH', '/profile', { email: 'email-invalido' })).status).toBe(422)
  expect((await api(page, 'PATCH', '/profile', { ensName: 'sem-dominio' })).status).toBe(422)
  expect((await api(page, 'PATCH', '/profile', { usePrimaryForSecondary: 'sim' })).status).toBe(422)
  expect((await api(page, 'PATCH', '/wallets/wallet-ana-primary', { provider: 'Desconhecida' })).status).toBe(422)
  expect((await api(page, 'PATCH', '/wallets/wallet-ana-primary', { secondaryAddress: 'invalido' })).status).toBe(422)
  const profile = await api<{ email: string }>(page, 'GET', '/profile')
  expect(profile.data!.email).toBe('ana.ribeiro@kurio.dev')
})
