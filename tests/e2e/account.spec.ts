import { expect, test } from '@playwright/test'
import { api, loginUi, orderInput, prepare } from './support/api.js'

test.beforeEach(async ({ page }) => prepare(page))

test('avatar por URL valida protocolo, persiste e continua removido após salvar perfil', async ({ page }) => {
  await page.route('https://images.example.test/avatar.png', (route) => route.fulfill({ path: 'public/artwork/hero.png', contentType: 'image/png' }))
  await loginUi(page)
  const url = page.getByLabel('URL do avatar', { exact: true })
  await url.fill('javascript:alert(1)')
  await page.getByRole('button', { name: 'Usar URL do avatar' }).click()
  await expect(page.getByRole('alert')).toContainText('URL HTTP ou HTTPS válida')
  await url.fill('https://images.example.test/avatar.png')
  await page.getByRole('button', { name: 'Usar URL do avatar' }).click()
  await expect(page.getByAltText('Avatar do colecionador')).toHaveAttribute('src', 'https://images.example.test/avatar.png')
  await page.reload()
  await expect(url).toHaveValue('https://images.example.test/avatar.png')
  await page.getByRole('button', { name: 'Remover avatar', exact: true }).click()
  await expect(page.getByRole('img', { name: 'Sem avatar', exact: true })).toBeVisible()
  await expect(url).toHaveValue('')
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('img', { name: 'Sem avatar', exact: true })).toBeVisible()
})

