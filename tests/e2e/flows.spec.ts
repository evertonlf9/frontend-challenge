import { expect, test, type Page } from '@playwright/test'
import { api, loginUi, prepare } from './support/api.js'

interface Nft { id: string; name: string; priceEth: string; available: number }
async function addNft(page: Page, quantity = 1) {
  const result = await api<{ items: Nft[] }>(page, 'GET', '/nfts?network=ethereum&pageSize=24')
  const nft = result.data!.items.find((item) => item.available >= 3)!
  await page.goto('/nft/' + nft.id)
  await expect(page.getByRole('heading', { name: nft.name, exact: true })).toBeVisible()
  await page.getByLabel('Quantidade', { exact: true }).fill(String(quantity))
  await page.getByRole('button', { name: 'COMPRAR', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Carrinho de NFTs' })).toBeVisible()
  return nft
}
async function checkout(page: Page) {
  await loginUi(page)
  const nft = await addNft(page)
  await page.goto('/checkout')
  await page.getByRole('button', { name: 'Conectar carteira simulada' }).click()
  await expect(page.getByText(/Carteira conectada à rede/)).toBeVisible()
  return nft
}
async function review(page: Page) {
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Revisar pedido' })).toBeVisible()
}
async function socketReady(page: Page) {
  await page.evaluate(async () => {
    // @ts-expect-error Módulo Vite usado somente para aguardar o handshake real do transporte.
    const { socket } = await import('/src/lib/socket.ts')
    await new Promise<void>((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('Socket não conectou')), 5000)
      socket.once('health.ok', () => { clearTimeout(timer); resolve() })
      if (socket.connected) socket.emit('health.check')
      else socket.once('connect', () => socket.emit('health.check'))
    })
  })
}
